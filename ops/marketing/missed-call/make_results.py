#!/usr/bin/env python3
"""HM-37: turn the filled call log into result drafts (HM-04). Drafts only; sends nothing.

Run from the repo root after the Thu 2026-12-03 calls are logged:
    python3 ops/marketing/missed-call/make_results.py
Writes ops/marketing/missed-call/result-drafts.md. Every fact is copied from
call-log-template.csv; a practice is skipped unless all 3 calls are logged.
Standard library only.
"""
import csv, datetime as dt, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LOG = os.path.join(HERE, "call-log-template.csv")
TEST = os.path.join(HERE, "missed-call-test.csv")
OUT = os.path.join(HERE, "result-drafts.md")
RESULTS = {"answered", "voicemail", "no-answer", "ivr-menu", "busy", "disconnected"}
CAT = {"dental": "dentist", "chiropractic": "chiropractor", "med spa": "med spa", "physical therapy": "physical therapist"}
CALLS = ["1-lunch", "2-late-afternoon", "3-after-close"]
PHRASE = {
    "voicemail": "went to voicemail",
    "no-answer": "rang out with no answer",
    "ivr-menu": "reached a phone menu",
    "busy": "got a busy signal",
    "disconnected": "didn't connect",
}

def when(r):
    d = r["date"].strip()
    try:
        day = dt.date.fromisoformat(d).strftime("%A")
    except ValueError:
        day = d
    t = r["time_cst"].strip()
    return f"{day} {t}".strip()

def outcome(r):
    res = r["result"].strip().lower()
    if res == "answered":
        n = r["rings_or_seconds_to_answer"].strip()
        return f"answered ({n})" if n else "answered"
    return PHRASE[res]

def extra(rows):
    """One line on voicemail or callback, only from logged values."""
    bits = []
    cb = [r for r in rows if r["callback_time_cst"].strip()]
    if cb:
        bits.append("You called back " + ", ".join(r["callback_time_cst"].strip() for r in cb) + ".")
    vm = [r for r in rows if r["result"].strip().lower() == "voicemail" and r["voicemail_greeting"].strip()]
    if vm:
        g = vm[0]["voicemail_greeting"].strip().lower()
        bits.append({"yes": "The voicemail greeting gave your hours and another way to reach you.",
                     "partial": "The voicemail greeting gave some, but not all, of your hours and other ways to reach you.",
                     "no": "The voicemail greeting didn't give hours or another way to reach you."}.get(g, ""))
    elif any(r["result"].strip().lower() in ("voicemail", "no-answer") for r in rows) and not cb:
        bits.append("No one called back during the test.")
    return " ".join(b for b in bits if b)

def main():
    log = list(csv.DictReader(open(LOG, newline="")))
    test = {r["test_id"]: r for r in csv.DictReader(open(TEST, newline=""))}
    by = {}
    for r in log:
        by.setdefault(r["test_id"], []).append(r)
    ready, skipped, problems = [], [], []
    for tid, t in test.items():
        rows = {r["call"]: r for r in by.get(tid, [])}
        logged = [rows[c] for c in CALLS if c in rows and rows[c]["result"].strip()]
        bad = [r for r in logged if r["result"].strip().lower() not in RESULTS]
        if bad:
            problems.append(f"{tid}: unknown result value(s) {[r['result'] for r in bad]}")
            continue
        if len(logged) < 3:
            skipped.append(f"{tid} {t['business']}: {len(logged)} of 3 calls logged")
            continue
        ready.append((t, logged))
    out = ["# Result drafts (HM-04), generated by make_results.py\n",
           "**Drafts only. Nothing has been sent.** Jilsha sends, submits and calls herself, only after the $49 go and with payment set up (`ops/board/DECISIONS-2026-12-03.md`). Slots: `send-master.md` Plan B. Every fact below is copied from `call-log-template.csv`; re-read the log row before sending.\n",
           f"Generated {dt.datetime.now().strftime('%Y-%m-%d %H:%M')} (machine clock). Ready: {len(ready)}. Skipped: {len(skipped)}. Problems: {len(problems)}.\n"]
    if problems:
        out.append("## Fix in the log first\n\n" + "\n".join("- " + p for p in problems) + "\n")
    if skipped:
        out.append("## Not ready (fewer than 3 calls logged)\n\n" + "\n".join("- " + s for s in skipped) + "\n")
    order = {"email": 0, "form": 1, "callback": 2}
    ready.sort(key=lambda x: (order.get(x[0]["result_channel"], 9), x[0]["test_id"]))
    for t, rows in ready:
        calls = "; ".join(f"{when(r)}, {outcome(r)}" for r in rows)
        all_ok = all(r["result"].strip().lower() == "answered" for r in rows)
        line2 = extra(rows)
        p, ch = t["business"], t["result_channel"]
        out.append(f"## {t['test_id']} {p} ({t['category']}, {t['city']}) — {ch}\n")
        if ch == "email":
            out.append(f"To: {t['result_email']}\n")
            body = f"Hi there,\n\nThis week I called {p} three times as a new patient would: {calls}." + (f" {line2}" if line2 else "")
            if all_ok:
                body += "\n\nAll three calls were answered. Nicely done."
            else:
                body += f"\n\nIf that's useful, I can send the full write-up (calls, voicemail and callback, your Google reviews, and what AI tools say for \"{CAT.get(t['category'].lower(), t['category'].lower())} in {t['city']}\") for $49. Want it?"
            body += "\n\nJilsha Jose, VilouraAI\nNot interested? Reply \"no\" and I won't email again.\nVilouraAI, 357 E Corporate Dr, Lewisville, TX"
            out.append(f"```\nSubject: We called {p} 3 times this week\n\n{body}\n```\n")
        elif ch == "form":
            out.append(f"Form: {t['form_url']}\n")
            ask = " All three were answered. Nicely done, and no reply needed." if all_ok else " Happy to send the full write-up (calls, voicemail, reviews, what AI tools say, and 3 cheap fixes) for $49. Want it? If not, no reply needed."
            msg = f"Hi, I'm Jilsha with VilouraAI in Lewisville. This week I called {p} three times as a new patient would: {calls}.{ask}"
            out.append(f"```\n{msg}\n```\n")
        else:
            out.append(f"Phone: {t['phone_to_call']} (once, mid-morning; script in `result-by-form-or-phone.md`)\n")
            out.append(f"Result summary to say: \"{calls}.\"" + (" All answered: thank them, no offer." if all_ok else "") + "\n")
        if re.search(r"https?://", "\n".join(out[-1:])) and ch != "form":
            problems.append(f"{t['test_id']}: link in draft")
    open(OUT, "w").write("\n".join(out) + "\nDONE\n")
    print(f"ready {len(ready)}, skipped {len(skipped)}, problems {len(problems)} -> {OUT}")
    return 1 if problems else 0

if __name__ == "__main__":
    sys.exit(main())
